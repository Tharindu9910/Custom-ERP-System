import { useState } from 'react';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { CreateChiefSchema } from '@erp/shared';
import { Icon } from '@/shared/components/Icon';
import { Notice } from '@/shared/components/Notice';
import { apiClient } from '@/shared/api/client';
import { apiError } from '@/shared/api/errors';
import { queryKeys } from '@/shared/api/query-keys';
import { formatDateTime } from '@/shared/lib/format';

interface Candidate {
  employee_id: string;
  employee_code: string;
  full_name: string;
  designation: string | null;
  phone: string | null;
}

interface CreatedChief {
  full_name: string;
  username: string;
  temporary_password: string;
  expires_at: string;
}

/**
 * Create Chief Profile (prototype). The temporary password is generated by the
 * server and shown once here to hand over; it expires in 72 hours and must be
 * changed at first login (no email service — Docs/decisions/0001).
 */
export function ChiefProfilePage() {
  const qc = useQueryClient();
  const [search, setSearch] = useState('');
  const [selected, setSelected] = useState<Candidate | null>(null);
  const [email, setEmail] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [created, setCreated] = useState<CreatedChief | null>(null);
  const [copied, setCopied] = useState(false);

  const { data: employees = [], isLoading } = useQuery({
    queryKey: queryKeys.employees.withoutAccount({ search }),
    queryFn: async () => (await apiClient.get<{ data: Candidate[] }>('/users/chief-candidates', { params: { search: search || undefined } })).data.data,
  });

  const create = useMutation({
    mutationFn: async () => (await apiClient.post<{ data: CreatedChief }>('/users/chief', { employee_id: selected!.employee_id, email })).data.data,
    onSuccess: (res) => {
      setCreated(res);
      setSelected(null);
      setEmail('');
      void qc.invalidateQueries({ queryKey: ['employees'] });
      // A chief profile is a new user account
      void qc.invalidateQueries({ queryKey: queryKeys.users.all() });
    },
    onError: (e) => setError(apiError(e).message),
  });

  const submit = () => {
    setError(null);
    const parsed = CreateChiefSchema.safeParse({ employee_id: selected?.employee_id, email });
    if (!parsed.success) return setError(parsed.error.issues[0]?.message ?? 'Check the details');
    create.mutate();
  };

  const copy = async () => {
    if (!created) return;
    try {
      await navigator.clipboard.writeText(`Username: ${created.username}\nTemporary password: ${created.temporary_password}`);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      /* clipboard unavailable */
    }
  };

  return (
    <div className="mx-auto max-w-4xl space-y-6">
      {created && (
        <div className="rounded-lg border border-emerald-200 bg-emerald-50 p-5">
          <div className="flex items-start justify-between gap-4">
            <div>
              <h3 className="flex items-center gap-2 text-sm font-bold text-emerald-900">
                <Icon name="checkCircle" className="h-4 w-4" />
                Chief profile created for {created.full_name}
              </h3>
              <p className="mt-1 text-xs text-emerald-800">
                Give these details to the chief in person. This password is shown only once, stops working on {formatDateTime(created.expires_at)}, and must be
                changed at first login.
              </p>
            </div>
            <button onClick={() => setCreated(null)} className="text-emerald-700 hover:text-emerald-900" aria-label="Dismiss">
              <Icon name="x" />
            </button>
          </div>
          <div className="mt-4 grid grid-cols-1 gap-3 sm:grid-cols-2">
            <div className="rounded border border-emerald-200 bg-white p-3">
              <p className="text-[10px] font-bold uppercase tracking-wider text-slate-400">Username</p>
              <p className="font-mono text-sm font-semibold text-slate-900">{created.username}</p>
            </div>
            <div className="rounded border border-emerald-200 bg-white p-3">
              <p className="text-[10px] font-bold uppercase tracking-wider text-slate-400">Temporary password</p>
              <p className="font-mono text-sm font-semibold tracking-wider text-slate-900">{created.temporary_password}</p>
            </div>
          </div>
          <button onClick={() => void copy()} className="mt-3 inline-flex items-center gap-1.5 text-xs font-semibold text-emerald-800 hover:underline">
            <Icon name="copy" className="h-3.5 w-3.5" />
            {copied ? 'Copied' : 'Copy details'}
          </button>
        </div>
      )}

      <div className="overflow-hidden rounded-lg border border-gray-200 bg-white shadow-sm">
        <div className="flex items-center gap-3 border-b border-gray-200 bg-gray-50 px-6 py-5">
          <Icon name="userCircle" className="h-6 w-6 text-gray-700" />
          <h2 className="text-lg font-bold tracking-wider text-gray-900">CREATE CHIEF PROFILE</h2>
        </div>

        <div className="grid grid-cols-1 gap-8 p-6 md:grid-cols-2">
          <div className="space-y-6">
            <div>
              <label className="mb-2 block text-sm font-medium text-gray-700">Search Employee</label>
              <div className="relative">
                <Icon name="search" className="pointer-events-none absolute left-3 top-1/2 h-5 w-5 -translate-y-1/2 text-gray-400" />
                <input
                  type="text"
                  placeholder="Enter Employee ID or Name..."
                  value={search}
                  onChange={(e) => setSearch(e.target.value)}
                  className="block w-full rounded-md border border-gray-300 py-2 pl-10 pr-3 shadow-sm focus:border-blue-500 focus:outline-none focus:ring-1 focus:ring-blue-500 sm:text-sm"
                />
              </div>
            </div>
            <div className="h-64 overflow-y-auto rounded-md border border-gray-200 bg-white">
              {isLoading ? (
                <div className="mt-10 p-4 text-center text-sm text-gray-400">Loading…</div>
              ) : employees.length === 0 ? (
                <div className="mt-10 p-4 text-center text-sm text-gray-500">No employees found without a profile.</div>
              ) : (
                <ul className="divide-y divide-gray-200">
                  {employees.map((emp) => (
                    <li
                      key={emp.employee_id}
                      onClick={() => {
                        setSelected(emp);
                        setError(null);
                      }}
                      className={`flex cursor-pointer items-center justify-between p-3 transition-colors hover:bg-gray-50 ${
                        selected?.employee_id === emp.employee_id ? 'border-l-4 border-blue-500 bg-blue-50' : ''
                      }`}
                    >
                      <div>
                        <div className="text-sm font-medium text-gray-900">{emp.full_name}</div>
                        <div className="text-xs text-gray-500">
                          {emp.employee_code} • {emp.designation ?? '—'}
                        </div>
                      </div>
                    </li>
                  ))}
                </ul>
              )}
            </div>
          </div>

          <div className="space-y-6 rounded-lg border border-gray-200 bg-gray-50 p-6">
            {selected ? (
              <div className="space-y-5">
                <div>
                  <h3 className="mb-3 flex items-center text-sm font-semibold uppercase tracking-wider text-gray-900">
                    <Icon name="eye" className="mr-2 h-4 w-4 text-gray-500" /> Employee Details
                  </h3>
                  <div className="space-y-2 rounded border border-gray-200 bg-white p-3 text-sm">
                    <Row label="Name" value={selected.full_name} />
                    <Row label="Emp ID" value={selected.employee_code} />
                    <Row label="Designation" value={selected.designation ?? '—'} />
                    <Row label="Phone" value={selected.phone ?? '—'} />
                  </div>
                </div>
                <div className="space-y-4 border-t border-gray-200 pt-4">
                  <div>
                    <label className="mb-1 flex items-center text-sm font-medium text-gray-700">
                      <Icon name="mail" className="mr-1 h-4 w-4 text-gray-400" /> Email (Username)
                    </label>
                    <input
                      type="email"
                      required
                      value={email}
                      onChange={(e) => setEmail(e.target.value)}
                      className="block w-full rounded-md border border-gray-300 py-2 px-3 shadow-sm focus:border-blue-500 focus:outline-none focus:ring-1 focus:ring-blue-500 sm:text-sm"
                      placeholder="chief@example.com"
                    />
                  </div>
                  <div className="flex items-start gap-2 text-xs text-gray-500">
                    <Icon name="key" className="mt-0.5 h-4 w-4 shrink-0 text-gray-400" />A temporary password is generated for you to hand over. The chief must
                    change it at first login.
                  </div>
                </div>
                {error && <Notice tone="error">{error}</Notice>}
                <div className="pt-4">
                  <button
                    onClick={submit}
                    disabled={create.isPending}
                    className="flex w-full justify-center rounded-md bg-slate-900 px-4 py-2.5 text-sm font-medium text-white shadow-sm transition-colors hover:bg-slate-800 disabled:opacity-50"
                  >
                    {create.isPending ? 'Creating…' : 'Create Chief Profile'}
                  </button>
                </div>
              </div>
            ) : (
              <div className="flex h-full flex-col items-center justify-center py-12 text-gray-500">
                <Icon name="userCircle" className="mb-4 h-12 w-12 text-gray-300" />
                <p>Select an employee from the list</p>
                <p className="mt-1 text-sm">to create their Chief Profile.</p>
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}

function Row({ label, value }: { label: string; value: string }) {
  return (
    <div className="grid grid-cols-3">
      <span className="text-gray-500">{label}:</span> <span className="col-span-2 font-medium">{value}</span>
    </div>
  );
}
